/**
 * Claude Design System tokens.json: lists of {name, value, usage}, colors
 * with a light and a dark theme. Only hex and rgba values, so every token
 * survives the importer.
 */
export function toDesignTokens(theme: Theme) {
  const mode = theme.config.color.mode;
  const other: Mode = mode === 'light' ? 'dark' : 'light';
  const themes = [
    { id: mode, name: mode === 'light' ? 'Light' : 'Dark' },
    { id: other, name: other === 'light' ? 'Light' : 'Dark' },
  ];
  const colorTokens: { name: string; value: Record<string, string>; usage: string }[] = [];
  const keys = Object.keys(theme.colors.light).filter((k) => !k.startsWith('shadow') && k !== 'image-scrim' && k !== 'focus-ring');
  for (const k of keys) {
    const fix = (v: string) => (v === 'transparent' ? '#00000000' : v);
    colorTokens.push({ name: k, value: { [mode]: fix(theme.colors[mode][k]), [other]: fix(theme.colors[other][k]) }, usage: USAGE[k] ?? '' });
  }
  for (const [name, scale] of Object.entries(theme.scales)) {
    for (const [step, hex] of Object.entries(scale)) {
      if (step === 'anchor') continue;
      colorTokens.push({ name: `${name}-${step}`, value: { [mode]: hex as string }, usage: `${name} scale, step ${step}.` });
    }
  }
  const t = theme.type;
  const groups = [
    {
      name: 'Display', family: 'display',
      styles: (['display-2xl', 'display-xl', 'display-l', 'display-m'] as const).map((k) => {
        const [size, lh] = TYPE_SCALE[k];
        return { name: k, fontSize: `${size}px`, lineHeight: `${Math.round(size * lh)}px`, fontWeight: t.displayWeight, letterSpacing: t.displayTracking };
      }),
    },
    {
      name: 'Text', family: 'body',
      styles: (['h1', 'h2', 'h3', 'body-l', 'body', 'body-s', 'label', 'caption', 'overline'] as const).map((k) => {
        const [size, lh, w, tr] = TYPE_SCALE[k];
        return { name: k, fontSize: `${size}px`, lineHeight: `${Math.round(size * (lh as number))}px`, fontWeight: w as number, letterSpacing: tr as string };
      }),
    },
    {
      name: 'Code', family: 'mono',
      styles: [{ name: 'code', fontSize: '13px', lineHeight: '20px', fontWeight: 400 }],
    },
  ];
  const r = theme.radius;
  return {
    name: theme.config.name,
    version: 1,
    meta: { source: 'ui-system', config: theme.config },
    color: { themes, tokens: colorTokens },
    type: {
      fonts: [],
      families: { display: t.stacks.display, body: t.stacks.body, mono: t.stacks.mono },
      groups,
    },
    spacing: {
      tokens: [4, 8, 12, 16, 20, 24, 32, 40, 48, 64, 80, 96].map((v, i) => ({ name: `space-${i + 1}`, value: `${v}px`, usage: i < 3 ? 'Inside controls and tight groups.' : i < 7 ? 'Card padding and gaps between related blocks.' : 'Section spacing.' }))
        .concat([
          { name: 'control-sm', value: theme.shared['h-sm'], usage: 'Small control height.' },
          { name: 'control-md', value: theme.shared['h-md'], usage: 'Default control height (touch target).' },
          { name: 'control-lg', value: theme.shared['h-lg'], usage: 'Large control height, hero CTAs.' },
        ]),
    },
    radius: {
      tokens: (['chip', 'control', 'field', 'card', 'panel', 'media', 'shell', 'inner'] as const).map((k) => ({
        name: `radius-${k}`,
        value: `${Math.min(r[k] as number, 999)}px`,
        usage: RADIUS_USAGE[k],
      })),
    },
    shadow: {
      tokens: ['sm', 'md', 'lg', 'float'].map((s) => ({ name: `shadow-${s}`, value: theme.colors[mode][`shadow-${s}`], usage: s === 'float' ? 'Floating navs and docks.' : s === 'lg' ? 'Drawers, dialogs, popovers.' : s === 'md' ? 'Raised cards, menus.' : 'Resting cards, inputs.' })),
    },
  };
}

/** Resolved values as plain JSON (useful for Framer variables or native apps). */
export function toJSON(theme: Theme) {
  return {
    name: theme.config.name,
    config: theme.config,
    fontsUrl: theme.fontsUrl,
    light: theme.vars('light'),
    dark: theme.vars('dark'),
  };
}
