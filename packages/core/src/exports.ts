import type { Mode } from './config';
import { NEUTRAL_STEPS, SCALE_STEPS } from './color';
import { TYPE_SCALE } from './type';
import type { Theme, Vars } from './theme';

const HEADER = '/* Generated by UI System. Edit ui.config.json and run `ui-system build`, never this file. */';

const block = (selector: string, vars: Vars) =>
  `${selector} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`;

const prefixed = (vars: Vars) => Object.fromEntries(Object.entries(vars).map(([k, v]) => [`--uis-${k}`, v]));

export interface CSSOptions {
  /** Where the default-mode variables go. */
  selector?: string;
  /** Include the Google Fonts @import line. */
  fonts?: boolean;
  /** Also follow the OS color scheme when no data-uis-mode is set. */
  system?: boolean;
}

/** Plain CSS variables for any stack: plain HTML, Framer, Shopify, Next.js. */
export function toCSS(theme: Theme, opts: CSSOptions = {}): string {
  const { selector = ':root', fonts = true, system = false } = opts;
  const mode: Mode = theme.config.color.mode;
  const other: Mode = mode === 'light' ? 'dark' : 'light';
  const base = theme.vars(mode);
  const parts = [HEADER];
  if (fonts) parts.push(`@import url('${theme.fontsUrl}');`);
  parts.push(block(selector, base));
  parts.push(block(`[data-uis-mode="${other}"]${other === 'dark' ? ', .dark' : ', .light'}`, prefixed(theme.colors[other])));
  parts.push(block(`[data-uis-mode="${mode}"]${mode === 'dark' ? ', .dark' : ', .light'}`, prefixed(theme.colors[mode])));
  if (system && mode === 'light') {
    parts.push(`@media (prefers-color-scheme: dark) {\n${block(`  ${selector}:not([data-uis-mode="light"]):not(.light)`, prefixed(theme.colors.dark))}\n}`);
  }
  return parts.join('\n\n') + '\n';
}

const SEMANTIC = [
  'bg', 'surface', 'surface-2', 'surface-3', 'line', 'line-strong', 'ink', 'ink-2', 'ink-3', 'inverse', 'inverse-ink', 'on-image', 'focus',
  ...['primary', 'accent', 'success', 'warning', 'danger', 'info'].flatMap((r) => [r, `${r}-hover`, `${r}-ink`, `${r}-soft`, `${r}-soft-ink`, `${r}-text`]),
];

/**
 * Tailwind v4 theme. It maps utilities to the runtime variables, so
 * `bg-primary rounded-control font-display shadow-float` follow whatever
 * theme is active, including live changes and dark mode.
 */
export function toTailwind(): string {
  const lines: string[] = [];
  for (const name of SEMANTIC) lines.push(`  --color-${name}: var(--uis-${name});`);
  for (const r of ['primary', 'accent', 'success', 'warning', 'danger', 'info']) {
    for (const s of SCALE_STEPS) lines.push(`  --color-${r}-${s}: var(--uis-${r}-${s});`);
  }
  for (const s of NEUTRAL_STEPS) lines.push(`  --color-neutral-${s}: var(--uis-neutral-${s});`);
  for (const r of ['chip', 'control', 'field', 'card', 'panel', 'media', 'shell', 'avatar']) lines.push(`  --radius-${r}: var(--uis-r-${r});`);
  lines.push('  --font-display: var(--uis-font-display);', '  --font-sans: var(--uis-font-body);', '  --font-mono: var(--uis-font-mono);');
  for (const s of ['sm', 'md', 'lg', 'float']) lines.push(`  --shadow-${s}: var(--uis-shadow-${s});`);
  lines.push('  --ease-out-soft: var(--uis-ease-out);', '  --ease-in-out-soft: var(--uis-ease-in-out);');
  for (const s of ['sm', 'md', 'lg']) lines.push(`  --spacing-control-${s}: var(--uis-h-${s});`);
  return `${HEADER}\n/* Import after tailwindcss and theme.css:  @import "tailwindcss"; @import "./theme.css"; @import "./tailwind.css"; */\n\n@theme inline {\n${lines.join('\n')}\n}\n\n@custom-variant dark (&:where([data-uis-mode="dark"], [data-uis-mode="dark"] *, .dark, .dark *));\n`;
}

